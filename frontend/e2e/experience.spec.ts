import { test, expect } from "@playwright/test";
test.use({ storageState: { cookies: [], origins: [] } });

test("first visit chooses cinematic and the reference cursor damps, grows and leaves", async ({ page }) => {
  await page.goto("/");
  const dialog = page.getByRole("dialog", { name: "Make yourself comfortable." });
  await expect(dialog).toBeVisible();
  await expect(page.getByRole("radio", { name: /^Cinematic/ })).toBeChecked();
  await page.screenshot({ path: "test-results/experience-choice-desktop.png" });
  await page.getByRole("button", { name: "Continue to Clyra", exact: true }).press("Enter");
  await expect(dialog).not.toBeVisible();
  await expect(page.locator("html")).toHaveAttribute("data-experience", "cinematic");
  await expect(page.getByRole("heading", { name: "Care in context." })).toBeVisible();
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(1000);
  await page.screenshot({ path: "test-results/cinema-hero-desktop.png" });
  
  const cursor = page.locator(".cursor-follower");
  await page.mouse.move(10, 10);
  await expect(cursor).toHaveAttribute("data-visible", "true");
  await page.mouse.move(1000, 500);
  await page.waitForTimeout(100);
  const x = await cursor.evaluate(el => new DOMMatrixReadOnly(getComputedStyle(el).transform).m41);
  expect(x).toBeGreaterThan(0);
  expect(x).toBeLessThan(950);
  expect(await page.evaluate(() => getComputedStyle(document.body).cursor)).toBe("none");
  expect(await cursor.evaluate(el => getComputedStyle(el).mixBlendMode)).toBe("difference");
  expect(await cursor.evaluate(el => getComputedStyle(el).pointerEvents)).toBe("none");
  const button = page.getByRole("button", { name: "Sign in", exact: true });
  await button.hover();
  await expect(cursor).toHaveAttribute("data-hot", "true");
  await expect.poll(() => cursor.evaluate(el => parseFloat(getComputedStyle(el).width))).toBe(56);
  await page.evaluate(() => window.dispatchEvent(new PointerEvent("pointerout", { relatedTarget: null })));
  await expect(cursor).toHaveAttribute("data-visible", "false");
  await page.mouse.move(100, 100);
  await page.keyboard.press("Tab");
  await expect(cursor).toHaveAttribute("data-visible", "false");
  await page.getByRole("switch", { name: "Easy reading mode off", exact: true }).press("Enter");
  await expect(page.locator("html")).toHaveAttribute("data-experience", "off");
  await expect(page.locator(".cinema-landing")).toHaveCount(0);
  await expect(cursor).toBeHidden();
  await page.reload();
  await expect(dialog).not.toBeVisible();
  await expect(page.locator("html")).toHaveAttribute("data-experience", "off");
});

