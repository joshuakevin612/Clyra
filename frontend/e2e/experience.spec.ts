test("ribbon stays alive at rest, reacts to the pointer, pauses offscreen and fully stops in easy reading", async ({ page }) => {
  await page.goto("/");
  await page.getByRole("button", { name: "Continue to Clyra", exact: true }).press("Enter");
  const ribbon = page.locator(".flow-hero-art canvas");
  await expect.poll(async () => Number(await ribbon.getAttribute("data-frame"))).toBeGreaterThan(2);
  const checksum = () => ribbon.evaluate(el => {
    const canvas = el as HTMLCanvasElement;
    const pixels = canvas.getContext("2d")!.getImageData(0, 0, canvas.width, canvas.height).data;
    let sum = 0;
    for (let i = 0; i < pixels.length; i += 32) sum = (sum * 31 + pixels[i]) >>> 0;
    return sum;
  });
  const still = await checksum();
  await page.waitForTimeout(800);
  expect(await checksum()).not.toBe(still);
  await page.mouse.move(1200, 200);
  await page.waitForTimeout(300);
  expect(await checksum()).not.toBe(still);
  await page.locator("#cinema-explore").scrollIntoViewIfNeeded();
  await page.waitForTimeout(150);
  const paused = await ribbon.getAttribute("data-frame");
  await page.waitForTimeout(250);
  expect(await ribbon.getAttribute("data-frame")).toBe(paused);
  await page.getByRole("switch", { name: "Easy reading mode off", exact: true }).press("Enter");
  await expect(page.locator(".continuity-ribbon, .flow-marquee")).toHaveCount(0);
  expect(await page.evaluate(() => document.getAnimations().length)).toBe(0);
});

test("traceability story stages headline, cards, then signature", async ({ page }) => {
  await page.goto("/");
  await page.getByRole("button", {name:"Continue to Clyra",exact:true}).press("Enter");
  const stage=page.locator(".cinema-orbit");
  const seek=async (progress:number) => {
    await stage.evaluate((el,p) => scrollTo(0,el.getBoundingClientRect().top+scrollY-64+(el.getBoundingClientRect().height-innerHeight+64)*p),progress);
  };
  await seek(.08);
  await expect.poll(()=>stage.evaluate(el=>Number(getComputedStyle(el).getPropertyValue("--title-opacity")))).toBeGreaterThan(.98);
  await page.screenshot({path:"test-results/trace-headline.png"});
  await seek(.58);
  await expect.poll(()=>stage.evaluate(el=>Number(getComputedStyle(el).getPropertyValue("--title-opacity")))).toBeLessThan(.01);
  await expect.poll(()=>page.locator(".orbit-world").evaluate(el=>Number(getComputedStyle(el).opacity))).toBeGreaterThan(.85);
  await seek(.96);
  await expect.poll(()=>stage.evaluate(el=>Number(getComputedStyle(el).getPropertyValue("--signature-offset")))).toBeLessThan(.01);
  await page.screenshot({path:"test-results/trace-signature.png"});
});
