test("cinematic native scroll is reversible, mobile reflows and touch has no follower", async ({ page }) => {
  await page.goto("/");
  await page.getByRole("button", { name: "Continue to Clyra", exact: true }).press("Enter");
  await page.evaluate(() => document.fonts.ready);
  const art = page.locator(".orbit-world");
  const position = () => art.evaluate(el => getComputedStyle(el).transform);
  const height = await page.evaluate(() => document.documentElement.scrollHeight);
  const start = await position();
  await page.locator(".cinema-orbit").evaluate(el => scrollTo(0, el.getBoundingClientRect().top + scrollY + (el.getBoundingClientRect().height - innerHeight) * 0.6));
  if (await page.evaluate(() => CSS.supports("animation-timeline", "view()"))) await expect.poll(position).not.toBe(start);
  await page.locator(".cinema-explore").screenshot({ path: "test-results/experience-scene-desktop.png" });
  await page.evaluate(() => scrollTo(0, 0));
  await expect.poll(position).toBe(start);
  expect(await page.evaluate(() => document.documentElement.scrollHeight)).toBe(height);
  await page.setViewportSize({ width: 320, height: 800 });
  await page.evaluate(() => document.fonts.ready);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.locator(".cinema-hero").screenshot({ path: "test-results/experience-scene-mobile.png" });
  await page.getByRole("switch", { name: "Easy reading mode off", exact: true }).press("Enter");
  await page.screenshot({ path: "test-results/easy-reading-mobile.png" });
  await page.getByRole("switch", { name: "Easy reading mode on", exact: true }).press("Enter");
  await expect(page.locator("html")).toHaveAttribute("data-experience", "cinematic");
  await page.dispatchEvent("body", "pointermove", { pointerType: "touch", clientX: 80, clientY: 100 });
  await expect(page.locator(".cursor-follower")).toHaveAttribute("data-visible", "false");
});

